#!/usr/bin/env bash
# Copy the app's interface (ui/) into the website's demo (site/demo/).
#
#   scripts/build-site-demo.sh
#
# The demo is the real app page running against a recording: replay.js
# answers the app's API calls from recording.js (made by
# scripts/record-demo.py). This script copies index.html, app.css, app.js,
# theme.js and icon.svg as they are now, marks each copy as generated,
# makes the page's asset paths relative (on pingtable.net "/app.js" is the
# site's own script), drops the web app manifest, and loads replay.js and
# recording.js before the app's scripts. Run it again whenever ui/ changes.
#
# The demo is a fixed list of files:
#   index.html app.css app.js theme.js icon.svg   (generated here)
#   fonts/*.woff2 fonts/OFL.txt                   (copied from ui/fonts/, when it exists)
#   replay.js recording.js                        (kept in site/demo/)
#
# Containment (see the top of site/demo/replay.js). The demo runs in a
# sandbox with an opaque origin, so:
#   - app.js runs as a classic deferred script, not a module: a module from an
#     opaque origin is a CORS request and fails. The copy is wrapped in a
#     strict function, which gives it a module's scope and strictness, and the
#     script fails if ui/app.js uses import, export or a top-level await.
#   - index.html gets a <meta> Content-Security-Policy (DEMO_CSP below), a
#     second layer under the header pingtable.net sends. A <meta> cannot carry
#     sandbox or frame-ancestors; those come from the header only.
#   - the script fails if the page has an inline script, an inline event
#     handler, a module script, a manifest, a file or link to another host
#     (the GitHub link excepted), a frame, a plug-in, a <base>, a <style>,
#     a refresh, or a form that is not method="dialog"; if ui/fonts/ holds
#     anything but WOFF2 files and OFL.txt; or if app.css loads anything but
#     those fonts (fonts/<name>.woff2) and data: URLs.
# Nothing in site/demo/ changes unless every check passes.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
ui="$repo/ui"
out="$repo/site/demo"
mkdir -p "$out"

for f in replay.js recording.js; do
  [[ -f "$out/$f" ]] || { echo "site/demo/$f is missing" >&2; exit 1; }
done

note="Generated by scripts/build-site-demo.sh from ui/%s. Do not edit; change ui/ and run the script again."

python3 - "$ui" "$out" "$note" <<'PY'
import re, sys
from pathlib import Path

ui, out, note = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
COPIED = {"app.css", "app.js", "theme.js", "icon.svg"}
GITHUB = "https://github.com/lorincz-llc/pingtable"
# The demo's own policy, for the <meta>. pingtable.net sends the same in a header, plus
# frame-ancestors 'self' and sandbox allow-scripts allow-downloads.
DEMO_CSP = ("default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; style-src-elem 'self'; "
            "img-src 'self' data:; font-src 'self'; connect-src 'none'; frame-src 'none'; child-src 'none'; "
            "worker-src 'none'; manifest-src 'none'; object-src 'none'; media-src 'none'; "
            "form-action 'none'; base-uri 'none'; require-trusted-types-for 'script'; trusted-types default")
problems = []

# app.js: a module in ui/, a classic script here (see the top of this file).
js = (ui / "app.js").read_text(encoding="utf-8")
code = re.sub(r"/\*.*?\*/", "", js, flags=re.S)
code = re.sub(r"(?m)^\s*//.*$", "", code)
for pattern, what in [
    (r"(?m)^\s*import\b\s*[\w{*'\"]", "an import statement"),
    (r"(?m)^\s*export\b", "an export statement"),
    (r"\bimport\s*\.\s*meta\b", "import.meta"),
    (r"\bimport\s*\(", "a dynamic import()"),
    (r"(?m)^(?:await\b|for\s+await\b|(?:const|let|var)\s[^=\n]*=\s*await\b)", "a top-level await"),
]:
    if re.search(pattern, code):
        problems.append(f"ui/app.js has {what}; the demo runs it as a classic script")
app_js = ("// " + note % "app.js" + "\n"
          "// Wrapped in a strict function: a module's scope and strictness, as a classic script.\n"
          "(function () {\n'use strict';\n" + js.rstrip("\n") + "\n})();\n")

# Fonts: ui/fonts/ holds WOFF2 files and their licence, nothing else.
fonts = {}
if (ui / "fonts").is_dir():
    for f in sorted((ui / "fonts").iterdir()):
        if f.is_file() and f.name == "OFL.txt":
            fonts[f.name] = f.read_bytes()
        elif f.is_file() and re.fullmatch(r"[A-Za-z0-9_.-]+\.woff2", f.name):
            fonts[f.name] = f.read_bytes()
            if fonts[f.name][:4] != b"wOF2":
                problems.append(f"ui/fonts/{f.name} is not a WOFF2 file")
        else:
            problems.append(f"ui/fonts/{f.name}: only .woff2 files (named with letters, digits, . _ -) and OFL.txt belong there")

# app.css may load only those fonts (relative to the stylesheet) and data: URLs.
css = (ui / "app.css").read_text(encoding="utf-8")
if re.search(r"@import\b", css):
    problems.append("ui/app.css has an @import (the demo is a fixed list of files)")
for m in re.finditer(r"url\(\s*(['\"]?)(.*?)\1\s*\)", css):
    ref = m.group(2).strip()
    font = re.fullmatch(r"fonts/([A-Za-z0-9_.-]+\.woff2)", ref)
    if not ref.startswith("data:") and not (font and font.group(1) in fonts):
        problems.append(f"ui/app.css loads {ref}; the demo allows only fonts/<name>.woff2 from ui/fonts/ and data: URLs")
app_css = "/* " + note % "app.css" + " */\n" + css
theme_js = "// " + note % "theme.js" + "\n" + (ui / "theme.js").read_text(encoding="utf-8")

# icon.svg: the comment goes after the XML declaration, if there is one.
svg = (ui / "icon.svg").read_text(encoding="utf-8")
comment = "<!-- " + note % "icon.svg" + " -->"
m = re.match(r"\s*<\?xml[^>]*\?>\s*", svg)
svg = svg[: m.end()] + comment + "\n" + svg[m.end():] if m else comment + "\n" + svg

html = (ui / "index.html").read_text(encoding="utf-8")

# The manifest belongs to the installed app, not to a page on the website.
html, n = re.subn(r'[ \t]*<link[^>]*rel="manifest"[^>]*>\n?', "", html)

def relative(m):
    attr, path = m.group(1), m.group(2)
    name = path.lstrip("/")
    if name not in COPIED:
        problems.append(f'ui/index.html loads {path}, which the demo does not copy (add it to COPIED and to the file list)')
    return f'{attr}="{name}"'

html = re.sub(r'\b(href|src)="(/(?!/)[^"]*)"', relative, html)

# app.js as a classic script, deferred as a module is, so it still runs after the page is parsed.
def classic(m):
    attrs = m.group(1)
    if not re.search(r'\bsrc="app\.js"', attrs):
        return m.group(0)
    attrs = re.sub(r'\s+type="module"', "", attrs)
    return f"<script{attrs}{'' if re.search(r'\bdefer\b', attrs) else ' defer'}>"
html = re.sub(r"<script\b([^>]*)>", classic, html)

# replay.js must run before anything else asks the API; recording.js is
# deferred, so it is parsed after the page but still runs before app.js.
inject = '<script src="replay.js"></script>\n<script src="recording.js" defer></script>\n'
first_script = re.search(r"<script\b", html)
head_end = html.find("</head>")
if first_script and first_script.start() < head_end:
    html = html[: first_script.start()] + inject + html[first_script.start():]
else:
    html = html[:head_end] + inject + html[head_end:]

# The policy goes first in the head (after the charset), so it covers every file the page loads.
meta = f'<meta http-equiv="Content-Security-Policy" content="{DEMO_CSP}">\n'
charset = re.search(r"<meta charset=[^>]*>\n?", html, re.I)
head = re.search(r"<head\b[^>]*>\n?", html, re.I)
at = charset.end() if charset else head.end() if head else None
if at is None:
    problems.append("ui/index.html has no <head>")
else:
    html = html[:at] + meta + html[at:]

# The demo page is part of pingtable.net; search engines should list the site itself.
html = html.replace('<meta name="viewport"', '<meta name="robots" content="noindex">\n<meta name="viewport"', 1)
html = re.sub(r"<body([^>]*)>", r'<body\1>\n<noscript><p class="demo-noscript">The pingtable demo replays a recording in your browser and needs JavaScript.</p></noscript>', html, count=1)

doctype = re.match(r"<!doctype html>\s*", html, re.I)
banner = "<!-- " + note % "index.html" + " -->\n"
html = html[: doctype.end()] + banner + html[doctype.end():] if doctype else banner + html

# What the page must not have. These hold for the finished page, whatever ui/index.html becomes.
head_html = html[: html.find("</head>")]
first_load = re.search(r"<(?:script|link|style)\b", head_html, re.I)
if not first_load or html.find(meta) < 0 or html.find(meta) > first_load.start():
    problems.append("the Content-Security-Policy <meta> must come before every script and style")
if not re.search(r'<script src="replay\.js"></script>', head_html) or re.search(r"<script\b", head_html).start() != head_html.find('<script src="replay.js">'):
    problems.append("replay.js must be the page's first script")
for m in re.finditer(r"<script\b([^>]*)>(.*?)</script>", html, re.S | re.I):
    if "src=" not in m.group(1) or m.group(2).strip():
        problems.append("an inline <script> (the demo's CSP allows only script files)")
    if re.search(r"\btype\s*=\s*[\"']?module", m.group(1), re.I):
        problems.append("a module script (a module cannot load in the demo's sandbox)")
if re.search(r"\son[a-z]+\s*=", html, re.I):
    problems.append("an inline event handler (on...=), which the demo's CSP blocks")
if re.search(r'\brel\s*=\s*["\']?manifest', html, re.I):
    problems.append("a web app manifest")
for m in re.finditer(r'\b(?:href|src|srcset|action|formaction|poster|data|background|xlink:href)\s*=\s*["\']?\s*((?:[a-z][a-z0-9+.-]*:|//)[^"\'\s>]*)', html, re.I):
    if not m.group(1).startswith(GITHUB):
        problems.append(f"a file or link from another host or scheme: {m.group(1)}")
if re.search(r"url\(\s*[\"']?\s*(?:[a-z][a-z0-9+.-]*:|//)", html, re.I):
    problems.append("a url() to another host in an inline style")
for tag in ["iframe", "frame", "frameset", "object", "embed", "applet", "portal", "fencedframe", "base", "style"]:
    if re.search(rf"<{tag}(?![\w-])", html, re.I):
        problems.append(f"a <{tag}> element")
if re.search(r"http-equiv\s*=\s*[\"']?refresh", html, re.I):
    problems.append("a refresh <meta>")
for m in re.finditer(r"<form\b([^>]*)>", html, re.I):
    if not re.search(r'\bmethod\s*=\s*["\']?dialog\b', m.group(1), re.I) or re.search(r"\baction\s*=", m.group(1), re.I):
        problems.append("a <form> that is not method=\"dialog\" (the sandbox blocks forms; replay.js closes dialog forms itself)")
if problems:
    sys.exit("build-site-demo: " + "; ".join(dict.fromkeys(problems)))
# Nothing is written unless every check passed.
import shutil
(out / "app.css").write_text(app_css, encoding="utf-8")
(out / "theme.js").write_text(theme_js, encoding="utf-8")
(out / "app.js").write_text(app_js, encoding="utf-8")
(out / "icon.svg").write_text(svg, encoding="utf-8")
(out / "index.html").write_text(html, encoding="utf-8")
if (out / "fonts").exists():
    shutil.rmtree(out / "fonts")
if fonts:
    (out / "fonts").mkdir()
    for name, data in fonts.items():
        (out / "fonts" / name).write_bytes(data)
PY

# With Node at hand, compile the copy exactly as the browser will: as a classic script.
if command -v node >/dev/null 2>&1; then
  node -e '
    const fs = require("fs"), vm = require("vm"), file = process.argv[1];
    try { new vm.Script(fs.readFileSync(file, "utf8"), { filename: file }); }
    catch (e) { console.error("build-site-demo: site/demo/app.js does not compile as a classic script: " + e.message); process.exit(1); }
  ' "$out/app.js"
else
  echo "build-site-demo: node not found; app.js was checked for module syntax but not compiled" >&2
fi

# Nothing else belongs in site/demo/: production serves exactly these files.
expected="app.css app.js icon.svg index.html recording.js replay.js theme.js"
[[ -d "$ui/fonts" ]] && expected="app.css app.js fonts icon.svg index.html recording.js replay.js theme.js"
actual="$(cd "$out" && ls | LC_ALL=C sort | tr '\n' ' ' | sed 's/ $//')"
if [[ "$actual" != "$expected" ]]; then
  echo "site/demo/ holds: $actual" >&2
  echo "expected exactly: $expected" >&2
  exit 1
fi
echo "site/demo/ rebuilt from ui/: $(cd "$out" && du -ch $expected | tail -1 | cut -f1) in $expected"
